package conversation

import "slices"

import "time"

// Status represents the current state of a conversation.
type Status string

const (
	// StatusActive indicates the conversation is currently active.
	StatusActive Status = "active"

	// StatusCompleted indicates the conversation has finished successfully.
	StatusCompleted Status = "completed"

	// StatusFailed indicates the conversation encountered a fatal error.
	StatusFailed Status = "failed"

	// StatusArchived indicates the conversation has been archived.
	StatusArchived Status = "archived"
)

// HeadlessTag marks conversations created by non-interactive headless runs
// (e.g. `swarm -p "<prompt>"`). Listing paths exclude conversations carrying
// this tag (via storage.Filter.ExcludeTags) so scripted/benchmark/sub-agent
// runs do not pollute the browsable TUI conversation picker or the agent-facing
// HistorySearch tool. The conversation is still persisted and reachable by ID.
const HeadlessTag = "headless"

// Conversation represents a complete conversation with all messages and metadata.
type Conversation struct {
	// ID is the unique identifier for this conversation.
	ID string `json:"id"`

	// CreatedAt is when the conversation was created (RFC3339 format).
	CreatedAt time.Time `json:"created_at"`

	// UpdatedAt is when the conversation was last updated (RFC3339 format).
	UpdatedAt time.Time `json:"updated_at"`

	// Mode is the currently active operating mode (e.g., "plan", "act", "auto").
	// This controls tool filtering and system instruction injection.
	Mode string `json:"mode"`

	// ModeHistory tracks all mode transitions as simple strings.
	ModeHistory []string `json:"mode_history,omitempty"`

	// OperatingModeState contains detailed state for the current operating mode.
	OperatingModeState *OperatingModeState `json:"operating_mode_state,omitempty"`

	// Status is the current status of the conversation.
	Status Status `json:"status"`

	// Messages contains all messages in the conversation.
	Messages []*Message `json:"messages"`

	// AgentMemories stores per-agent memory state.
	AgentMemories map[string]*AgentMemory `json:"agent_memories,omitempty"`

	// GroupState stores per-group state.
	GroupState map[string]*GroupState `json:"group_state,omitempty"`

	// ModeState stores per-mode state.
	ModeState *ModeState `json:"mode_state,omitempty"`

	// WorkspacePath is the absolute filesystem path of the workspace this
	// conversation belongs to. This is a first-class field used for efficient
	// directory-based storage and retrieval.
	WorkspacePath string `json:"workspace_path,omitempty"`

	// TraceID links this conversation to distributed tracing.
	TraceID string `json:"trace_id,omitempty"`

	// TotalTokens is a cumulative billing reference: the sum of msg.Tokens.Total
	// across all messages added to this conversation. Because each turn's
	// input_tokens already encodes the entire prior context, this field
	// double-counts on multi-turn conversations and MUST NOT be used for
	// compaction threshold decisions. Use CurrentContextSize for that purpose.
	TotalTokens int `json:"total_tokens"`

	// CurrentContextSize is the latest InputContextSize() from the most recent
	// assistant message (Input + CacheCreation + CacheRead). This is the
	// authoritative "how big is the conversation right now" number and is
	// the correct value to compare against the context window for compaction
	// decisions. Updated by AddMessage on every assistant message.
	CurrentContextSize int `json:"current_context_size"`

	// CurrentContextSizeEstimated is true after compaction until the next
	// provider response supplies authoritative input-token usage.
	CurrentContextSizeEstimated bool `json:"current_context_size_estimated,omitempty"`

	// TotalCostUSD is the cumulative cost in USD.
	TotalCostUSD float64 `json:"total_cost_usd"`

	// TotalOutputTokens is the cumulative number of provider-reported output
	// tokens. Unlike TotalTokens, this is not inflated by repeated input context
	// and is preserved when the active context is compacted.
	TotalOutputTokens int `json:"total_output_tokens,omitempty"`

	// WallTime is cumulative agent runtime for this conversation. It is stored
	// as nanoseconds so it survives process restarts and compaction boundaries.
	WallTime time.Duration `json:"wall_time,omitempty"`

	// Title is a human-readable title for the conversation.
	// This is typically generated by the naming agent based on conversation content.
	// If empty, the UI should display a preview of the first user message.
	Title string `json:"title,omitempty"`

	// Metadata contains custom fields.
	Metadata ConversationMetadata `json:"metadata"`

	// CompactionState persists compaction-critical state (file access, tasks,
	// mode context) as JSON so nothing is lost across restarts or compaction
	// cycles. Updated by the compaction service before and after compaction.
	CompactionState *CompactionState `json:"compaction_state,omitempty"`

	// BaseSystemPrompt is the stable system prompt this conversation started with.
	// Recorded at conversation creation time for auditability and debugging cache behavior.
	// NOT used at runtime — this field is diagnostic only. Allows reconstruction of
	// "what system prompt was in effect when this conversation was created?"
	BaseSystemPrompt string `json:"base_system_prompt,omitempty"`

	// Summary is a pre-computed, lightweight snapshot of the conversation used by
	// UI listings (sidebar, history view) so they can render rich rows without
	// loading the full Messages array. Maintained incrementally by AddMessage.
	// May be nil on legacy conversations — callers should rebuild with
	// RebuildSummary() when encountered.
	Summary *ConversationSummary `json:"summary,omitempty"`
}

// SummaryPreviewMaxLen caps the length of cached preview strings in
// ConversationSummary. Chosen to cover a one-line sidebar render without
// wasting bytes on multi-megabyte assistant replies.
const SummaryPreviewMaxLen = 240

// ConversationSummary holds pre-computed listing metadata so the UI can render
// thousands of rows without loading any Messages. Every field is updated in
// Conversation.AddMessage.
type ConversationSummary struct {
	MessageCount    int      `json:"message_count"`
	InputTokens     int      `json:"input_tokens,omitempty"`
	OutputTokens    int      `json:"output_tokens,omitempty"`
	ToolCallCount   int      `json:"tool_call_count,omitempty"`
	LastModel       string   `json:"last_model,omitempty"`
	ModelsUsed      []string `json:"models_used,omitempty"`
	LastPreview     string   `json:"last_preview,omitempty"`
	FirstUserPrompt string   `json:"first_user_prompt,omitempty"`

	// Recap is a short, LLM-generated free-text summary of the conversation
	// (a few sentences describing what was discussed / accomplished). Unlike the
	// other fields it is NOT derived heuristically in AddMessage — it is written
	// by the shared client metadata lifecycle and may be empty on conversations
	// that have not completed a substantive turn yet. Callers must guard "".
	Recap string `json:"recap,omitempty"`
}

// EnsureSummary returns a non-nil summary, allocating one on the conversation
// if needed.
func (c *Conversation) EnsureSummary() *ConversationSummary {
	if c.Summary == nil {
		c.Summary = &ConversationSummary{}
	}
	return c.Summary
}

// RebuildSummary recomputes the summary from scratch by scanning Messages.
// Used as a migration path for legacy conversations that lack Summary.
func (c *Conversation) RebuildSummary() {
	s := &ConversationSummary{}
	seen := make(map[string]bool)
	firstUserSet := false
	for _, m := range c.Messages {
		s.MessageCount++
			if m.Tokens != nil {
			s.InputTokens += m.Tokens.Input
			s.OutputTokens += m.Tokens.Output
		}
		s.ToolCallCount += len(m.ToolCalls)
		if m.Model != "" {
			s.LastModel = m.Model
			if !seen[m.Model] {
				seen[m.Model] = true
				s.ModelsUsed = append(s.ModelsUsed, m.Model)
			}
		}
		if !firstUserSet && m.Role == RoleUser && m.Content != "" {
			s.FirstUserPrompt = truncatePreview(m.Content, SummaryPreviewMaxLen)
			firstUserSet = true
		}
		if m.Role == RoleAssistant && m.Content != "" {
			s.LastPreview = truncatePreview(m.Content, SummaryPreviewMaxLen)
		} else if s.LastPreview == "" && m.Role == RoleUser && m.Content != "" {
			s.LastPreview = truncatePreview(m.Content, SummaryPreviewMaxLen)
		}
	}
	c.Summary = s
}

// truncatePreview returns up to max characters of s with an ellipsis when
// truncation actually happened. Runs on raw bytes — callers pass already-clean
// content. No allocation when s is already short enough.
func truncatePreview(s string, max int) string {
	if max <= 0 || len(s) <= max {
		return s
	}
	return s[:max-1] + "…"
}

