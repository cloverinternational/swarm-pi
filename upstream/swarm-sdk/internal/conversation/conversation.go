// EnsureCompactionState initializes CompactionState if nil.
func (c *Conversation) EnsureCompactionState() *CompactionState {
	if c.CompactionState == nil {
		c.CompactionState = &CompactionState{}
	}
	return c.CompactionState
}

// RecordCompaction increments compaction count and records timestamp.
func (c *Conversation) RecordCompaction(summary string) {
	cs := c.EnsureCompactionState()
	cs.CompactionCount++
	cs.LastCompactedAt = time.Now()
	cs.LastSummary = summary
}

// ActiveContextStartIndex returns the validated provider-visible boundary.
// A negative or out-of-range persisted value is treated as len(Messages), a
// fail-closed empty history, so corrupt metadata cannot silently re-expand an
// archived transcript into an oversized provider request.
func (c *Conversation) ActiveContextStartIndex() int {
	if c == nil {
		return 0
	}
	if c.CompactionState == nil {
		return 0
	}
	start := c.CompactionState.ActiveContextStart
	if start < 0 || start > len(c.Messages) {
		return len(c.Messages)
	}
	return start
}

// ActiveMessages returns a copy of the provider-visible slice header. Message
// pointers are intentionally shared with the canonical transcript, but callers
// may append to the returned slice without overwriting archived entries.
func (c *Conversation) ActiveMessages() []*Message {
	if c == nil {
		return nil
	}
	start := c.ActiveContextStartIndex()
	active := make([]*Message, len(c.Messages)-start)
	copy(active, c.Messages[start:])
	return active
}

// ReplaceActiveMessages replaces only the provider-visible suffix while
// preserving every archived message before the compaction boundary. It is used
// by message-repair code that may insert synthetic tool results.
func (c *Conversation) ReplaceActiveMessages(active []*Message) {
	if c == nil {
		return
	}
	start := c.ActiveContextStartIndex()
	full := make([]*Message, 0, start+len(active))
	full = append(full, c.Messages[:start]...)
	full = append(full, active...)
	c.Messages = full
	c.UpdatedAt = time.Now()
}

// AdvanceActiveContext appends a new compacted generation to the full durable
// transcript and atomically advances the provider-visible boundary to it.
func (c *Conversation) AdvanceActiveContext(messages []*Message, summary string, contextSize int) {
	if c == nil || len(messages) == 0 {
		return
	}
	start := len(c.Messages)
	for _, msg := range messages {
		c.AddMessage(msg)
	}
	cs := c.EnsureCompactionState()
	cs.ActiveContextStart = start
	cs.Generation++
	cs.CompactionCount++
	cs.LastCompactedAt = time.Now()
	cs.LastSummary = summary
	if contextSize < 0 {
		contextSize = 0
	}
	c.CurrentContextSize = contextSize
	c.CurrentContextSizeEstimated = true
}

// AddMessage adds a message to the conversation and updates metadata.
func (c *Conversation) AddMessage(msg *Message) {
	c.Messages = append(c.Messages, msg)
	c.UpdatedAt = time.Now()

	// Update token count
	if msg.Tokens != nil {
		c.TotalTokens += msg.Tokens.Total
		c.TotalOutputTokens += max(msg.Tokens.Output, 0)

		// Update current context size from assistant message's input context size.
		// InputContextSize() = Input + CacheCreation + CacheRead, which is the true
		// size of everything sent to the model on this turn (matches Anthropic's
		// input_tokens + cache_creation_input_tokens + cache_read_input_tokens).
		if msg.Role == RoleAssistant {
			if size := msg.Tokens.InputContextSize(); size > 0 {
				c.CurrentContextSize = size
				c.CurrentContextSizeEstimated = false
			}
		}
	}

	c.updateSummary(msg)

	// Record cheap terminal-state markers so message-stripped meta listings
	// (ListConversationsMeta) can still evaluate IsUnfinished without loading
	// the full Messages array. These mirror the last message's role and stop
	// reason and are refreshed on every AddMessage.
	if c.Metadata.Custom == nil {
		c.Metadata.Custom = make(map[string]any, 2)
	}
	c.Metadata.Custom[metaLastRole] = string(msg.Role)
	c.Metadata.Custom[metaLastStopReason] = messageStopReason(msg)
}

// updateSummary advances the cached summary by one message. Keeps listings
// O(1) on load by making this O(1) on save.
func (c *Conversation) updateSummary(msg *Message) {
	s := c.EnsureSummary()
	s.MessageCount++
	if msg.Tokens != nil {
		s.InputTokens += msg.Tokens.Input
		s.OutputTokens += msg.Tokens.Output
	}
	s.ToolCallCount += len(msg.ToolCalls)
	if msg.Model != "" {
		s.LastModel = msg.Model
		alreadySeen := slices.Contains(s.ModelsUsed, msg.Model)
		if !alreadySeen {
			s.ModelsUsed = append(s.ModelsUsed, msg.Model)
		}
	}
	if msg.Role == RoleUser && msg.Content != "" && s.FirstUserPrompt == "" {
		s.FirstUserPrompt = truncatePreview(msg.Content, SummaryPreviewMaxLen)
	}
	if msg.Content != "" && (msg.Role == RoleAssistant || msg.Role == RoleUser) {
		s.LastPreview = truncatePreview(msg.Content, SummaryPreviewMaxLen)
	}
}

// UpdateContextSize updates the current context size.
// This should be called with the latest input_tokens from an API response.
func (c *Conversation) UpdateContextSize(inputTokens int) {
	if inputTokens > 0 {
		c.CurrentContextSize = inputTokens
		c.CurrentContextSizeEstimated = false
	}
}

// GetMessages returns all messages in the conversation.
func (c *Conversation) GetMessages() []*Message {
	return c.Messages
}

// GetMessagesByRole returns all messages with the specified role.
func (c *Conversation) GetMessagesByRole(role Role) []*Message {
	var messages []*Message
	for _, msg := range c.Messages {
		if msg.Role == role {
			messages = append(messages, msg)
		}
	}
	return messages
}

// GetLastMessage returns the most recent message, or nil if no messages exist.
func (c *Conversation) GetLastMessage() *Message {
	if len(c.Messages) == 0 {
		return nil
	}
	return c.Messages[len(c.Messages)-1]
}

// MessageCount returns the total number of messages.
func (c *Conversation) MessageCount() int {
	return len(c.Messages)
}

// Metadata.Custom marker keys written by AddMessage so IsUnfinished can be
// evaluated on message-stripped conversations (ListConversationsMeta strips
// Messages to keep the TUI history menu cheap).
const (
	metaLastRole       = "last_role"
	metaLastStopReason = "last_stop_reason"
)

// naturalStopReasons are the terminal stop/finish reasons that indicate an
// assistant turn ended cleanly. Anything else (empty, max_tokens, length,
// error, canceled, content_filter, dangling tool_use, …) is treated as an
// unfinished turn.
var naturalStopReasons = map[string]struct{}{
	"end_turn":      {},
	"stop":          {},
	"stop_sequence": {},
}

// isNaturalStopReason reports whether reason is a natural terminal stop.
func isNaturalStopReason(reason string) bool {
	_, ok := naturalStopReasons[reason]
	return ok
}

// messageStopReason extracts the provider stop/finish reason recorded on a
// message. The canonical Message model does not carry a dedicated field, so
// providers stash it in Message.Metadata under "stop_reason" (Anthropic-style)
// or "finish_reason" (canonical/OpenAI-style). Returns "" when absent.
func messageStopReason(msg *Message) string {
	if msg == nil || msg.Metadata == nil {
		return ""
	}
	for _, key := range []string{"stop_reason", "finish_reason"} {
		if v, ok := msg.Metadata[key]; ok {
			if s, ok := v.(string); ok && s != "" {
				return s
			}
		}
	}
	return ""
}

// IsUnfinished reports whether this conversation's last turn did NOT reach a
// natural terminal stop. It must work even when messages are stripped (the TUI
// history menu uses ListConversationsMeta which strips messages) by falling
// back to persisted markers in Metadata.Custom ("last_role"/"last_stop_reason"
// written by AddMessage).
//
// Unfinished == true when ANY of:
//   - the last message role is user (the agent never produced a reply), OR
//   - the last assistant message has dangling tool calls (no completion), OR
//   - the last assistant message's stop reason is not natural
//     (natural = end_turn | stop | stop_sequence).
//
// An empty conversation (no messages and no markers) is NOT unfinished.
func (c *Conversation) IsUnfinished() bool {
	if c == nil {
		return false
	}

	// Live messages present: authoritative path.
	if len(c.Messages) > 0 {
		last := c.Messages[len(c.Messages)-1]
		if last == nil {
			return false
		}
		switch last.Role {
		case RoleAssistant:
			// Dangling tool calls => the loop was mid-flight.
			if len(last.ToolCalls) > 0 {
				return true
			}
			return !isNaturalStopReason(messageStopReason(last))
		default:
			// user/tool/system/peer last => no clean assistant terminal turn.
			return true
		}
	}

	// Message-stripped fallback: consult persisted markers.
	if c.Metadata.Custom != nil {
		if role, ok := c.Metadata.Custom[metaLastRole].(string); ok && role != "" {
			if role == string(RoleAssistant) {
				reason, _ := c.Metadata.Custom[metaLastStopReason].(string)
				return !isNaturalStopReason(reason)
			}
			return true
		}
	}

	// Empty conversation, no markers.
	return false
}

// GetOperatingMode returns the current operating mode, defaulting to "act" if not set.
func (c *Conversation) GetOperatingMode() string {
	if c.Mode == "" {
		return "act" // Default mode
	}
	return c.Mode
}

// SetOperatingMode sets the operating mode and records the transition.
func (c *Conversation) SetOperatingMode(newMode, reason, initiatedBy string) {
	oldMode := c.GetOperatingMode()

	// Update mode
	c.Mode = newMode
	c.ModeHistory = append(c.ModeHistory, newMode)
	c.UpdatedAt = time.Now()

	// Initialize OperatingModeState if needed
	if c.OperatingModeState == nil {
		c.OperatingModeState = &OperatingModeState{}
	}

	// Record transition
	transition := OperatingModeTransition{
		Timestamp:    time.Now(),
		From:         oldMode,
		To:           newMode,
		Reason:       reason,
		InitiatedBy:  initiatedBy,
		MessageIndex: len(c.Messages),
	}
	c.OperatingModeState.Transitions = append(c.OperatingModeState.Transitions, transition)
	c.OperatingModeState.CurrentMode = newMode
	c.OperatingModeState.EnteredAt = time.Now()
}

// RecordBlockedToolCall records a tool call that was blocked by mode filtering.
func (c *Conversation) RecordBlockedToolCall(toolName, mode, reason string) {
	if c.OperatingModeState == nil {
		c.OperatingModeState = &OperatingModeState{}
	}

	blocked := BlockedToolCall{
		Timestamp: time.Now(),
		ToolName:  toolName,
		Mode:      mode,
		Reason:    reason,
	}
	c.OperatingModeState.BlockedToolCalls = append(c.OperatingModeState.BlockedToolCalls, blocked)
	c.OperatingModeState.ToolsBlocked++
}

// GetModeTransitionCount returns the number of mode transitions in this conversation.
func (c *Conversation) GetModeTransitionCount() int {
	if c.OperatingModeState == nil {
		return 0
	}
	return len(c.OperatingModeState.Transitions)
}
