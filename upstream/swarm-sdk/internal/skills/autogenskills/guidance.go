// BuildSKILLSGuidance returns the skills-system guidance block for the system
// prompt. It teaches the agent the Hermes on-demand invocation model:
// the index is a compact name+description map; full instructions are pulled
// per-skill with SkillManage(action="view") exactly when needed.
//
// CONTRACT: Returns a block (≤3072 chars) suitable for system prompt injection.
// Returns empty string when mode is not enabled.
func BuildSKILLSGuidance(mode CreationMode, existingSkillNames []string) string {
	if !mode.IsEnabled() {
		return ""
	}

	var b strings.Builder

	b.WriteString("## Skill System\n\n")
	b.WriteString("Skills are reusable instruction sets for recurring tasks. ")
	b.WriteString("They follow the Hermes on-demand model: you see only a compact index ")
	b.WriteString("(name + description) in the system prompt. Full instructions are loaded ")
	b.WriteString("on demand by calling SkillManage(action=\"view\", name=\"...\"). ")
	b.WriteString("Never guess what a skill does from its description alone — always view it.\n\n")

	b.WriteString("### When to check skills (BEFORE starting work)\n\n")
	b.WriteString("At the start of any task requiring 3 or more distinct steps, ")
	b.WriteString("call SkillManage(action=\"list\") to check for relevant skills. ")
	b.WriteString("If the index shows a plausible match, view it immediately and follow ")
	b.WriteString("its instructions as the primary approach for this task. ")
	b.WriteString("Do not begin tool calls before checking — skills encode patterns that ")
	b.WriteString("prevent repeating expensive discovery work.\n\n")

	b.WriteString("### Consult multiple skills, not just one\n\n")
	b.WriteString("After finding one relevant skill, ask: does this task span more than one domain? ")
	b.WriteString("If so, check for complementary skills too. ")
	b.WriteString("Example: a task that requires both fixing Go code and updating a Linear issue ")
	b.WriteString("should check for skills matching both domains. ")
	b.WriteString("Read each relevant skill in full before deciding how to proceed. ")
	b.WriteString("The index description is a hint — not a substitute for the full instructions.\n\n")

	b.WriteString("### SkillManage tool actions\n\n")
	b.WriteString("- `list`: Discover available skills with name, version, and description. Always check before starting a complex task.\n")
	b.WriteString("- `view`: Load the full SKILL.md body. When you view a skill, follow its instructions for the current task. If it needs updating, patch it before continuing.\n")
	b.WriteString("- `create`: Last resort for a genuinely new class-level workflow. Never create merely because a task took several tool calls.\n")
	b.WriteString("- `patch`: Update a skill immediately when you find it incomplete, outdated, or wrong. Do not wait to be asked. Stale skills cause repeated mistakes.\n\n")
	b.WriteString("- `write_file`: Preserve narrow session detail under an existing umbrella in references/, templates/, scripts/, or assets/.\n")
	b.WriteString("- `review`: Record that you completed the review and found nothing reusable. This is a valid outcome; never manufacture a skill to satisfy a budget.\n\n")

	b.WriteString("### Correct invocation pattern\n\n")
	b.WriteString("1. Task starts → call `list` to check for relevant skills.\n")
	b.WriteString("2. Relevant skill found → call `view` to read full instructions.\n")
	b.WriteString("3. Task spans multiple domains → `view` each relevant skill before proceeding.\n")
	b.WriteString("4. Skill is stale or incomplete → `patch` it immediately, then continue.\n")
	b.WriteString("5. No existing umbrella fits → create one only if the learning generalizes beyond today's task.\n")
	b.WriteString("6. No reusable learning → call `review` with a short reason and continue without mutation.\n\n")

	b.WriteString("Avoid: ignoring the index, assuming skill content from the description, ")
	b.WriteString("relying on a single skill when multiple apply, or reading a skill without following it.\n")

	if len(existingSkillNames) > 0 {
		b.WriteString(fmt.Sprintf("\n**Current skill index (%d skills):** %s\n",
			len(existingSkillNames), strings.Join(existingSkillNames, ", ")))
		b.WriteString("Use `view` before creating a new skill to avoid duplicates.\n")
	} else {
		b.WriteString("\nNo skills exist yet. Create your first skill after completing a complex multi-step task.\n")
	}

	return b.String()
}

// BuildAutogenSkillIndex returns a compact listing of autogenerated skills
// for injection into the system prompt at session start.
//
// CONTRACT: Returns empty string when no autogen skills exist.
// Each skill is listed as: `name (vX.Y.Z): description`
// The agent must call SkillManage(action="view") to get full instructions.
func BuildAutogenSkillIndex(allSkills []*skills.Skill) string {
	var autogenSkills []*skills.Skill
	for _, s := range allSkills {
		if s.Source == "autogen" {
			autogenSkills = append(autogenSkills, s)
		}
	}

	if len(autogenSkills) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString("## Available Autogen Skills\n")
	b.WriteString("Call SkillManage(action=\"view\", name=\"...\") to load full instructions before using any skill.\n")

	// Progressive disclosure + bounded size (mirrors Hermes' compact index):
	// render only name + version + a truncated one-line description, and cap
	// the number of entries so the system prompt stays bounded regardless of
	// how many skills accumulate. The curator archives stale skills over time;
	// the cap is the in-prompt safety net while it catches up.
	rendered := autogenSkills
	omitted := 0
	if maxAutogenIndexSkills > 0 && len(rendered) > maxAutogenIndexSkills {
		omitted = len(rendered) - maxAutogenIndexSkills
		rendered = rendered[:maxAutogenIndexSkills]
	}

	for _, s := range rendered {
		version := s.Metadata.Version
		if version == "" {
			version = "?.?.?"
		}
		b.WriteString(fmt.Sprintf("- **%s** (v%s): %s\n", s.Metadata.Name, version, truncateSkillDesc(s.Metadata.Description)))
	}

	if omitted > 0 {
		b.WriteString(fmt.Sprintf("- _(%d more skill(s) omitted to bound prompt size; call SkillManage(action=\"list\") for the full set)_\n", omitted))
	}
	return b.String()
}

// maxAutogenIndexSkills caps how many autogen skills are rendered into the
// system-prompt index to keep it bounded. 0 means no cap.
const maxAutogenIndexSkills = 60

// maxAutogenDescChars bounds each skill's description in the index. Full
// instructions (and the full description) are available via the view action;
// the index is a hint, not the source of truth (Hermes progressive disclosure).
const maxAutogenDescChars = 120

// truncateSkillDesc collapses whitespace and trims a description to
// maxAutogenDescChars, appending an ellipsis when truncated.
func truncateSkillDesc(desc string) string {
	desc = strings.TrimSpace(strings.Join(strings.Fields(desc), " "))
	if maxAutogenDescChars > 0 && len(desc) > maxAutogenDescChars {
		return strings.TrimSpace(desc[:maxAutogenDescChars-1]) + "…"
	}
	return desc
}
