// SkillManageTool lets the LLM create skills via the autogenskills service.
//
// CONTRACT:
//   - Name is "SkillManage" (what the nudge tells the LLM to call).
//   - All creations go through Service.CreateSkill() which validates + writes.
//   - Returns the skill path on success, error details on failure.
//   - The service must be non-nil; construct via NewSkillManageTool.
type SkillManageTool struct {
	tools.BaseTool
	svc                    *Service
	mu                     sync.Mutex
	viewed                 map[string]bool
	requireReadBeforeWrite bool
	previewOnly            bool
}

// viewInstructionPageLimit leaves ample room under the agent's 100,000-byte
// tool-output cap for skill metadata, range provenance, and support-file names.
const viewInstructionPageLimit = 80_000

// NewSkillManageTool creates the tool.
// CONTRACT: svc must be non-nil.
func NewSkillManageTool(svc *Service) (*SkillManageTool, error) {
	if svc == nil {
		return nil, fmt.Errorf("autogenskills: SkillManageTool requires non-nil service")
	}
	return &SkillManageTool{svc: svc, viewed: make(map[string]bool)}, nil
}

// RestrictToPreview makes this tool read-only for a curator preview. The guard
// is enforced in Execute before dispatch, so no write helper can bypass it.
// Read operations do not update lifecycle usage in this mode.
func (t *SkillManageTool) RestrictToPreview() {
	t.mu.Lock()
	t.previewOnly = true
	t.mu.Unlock()
}

// NewPreviewSkillManageTool creates a SkillManage tool restricted to
// list/view/read_file/history/review without lifecycle usage bumps.
func NewPreviewSkillManageTool(svc *Service) (*SkillManageTool, error) {
	tool, err := NewSkillManageTool(svc)
	if err != nil {
		return nil, err
	}
	tool.RestrictToPreview()
	return tool, nil
}

func (t *SkillManageTool) isPreview() bool {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.previewOnly
}

// RequireReadBeforeWrite enables the stricter autonomous-review contract:
// existing skills must be viewed in this tool session before they can be
// patched, extended, or archived.
func (t *SkillManageTool) RequireReadBeforeWrite() {
	t.mu.Lock()
	t.requireReadBeforeWrite = true
	t.mu.Unlock()
}

func (t *SkillManageTool) ensureWritable(name string) string {
	t.mu.Lock()
	required := t.requireReadBeforeWrite
	viewed := t.viewed[name]
	t.mu.Unlock()
	if !required {
		return ""
	}
	if curator := t.svc.GetCurator(); curator != nil && curator.IsPinned(name) {
		return fmt.Sprintf("skill %q is pinned; autonomous review cannot modify it", name)
	}
	if !viewed {
		return fmt.Sprintf("skill %q must be viewed before autonomous modification", name)
	}
	return ""
}

// Name returns "SkillManage".
func (t *SkillManageTool) Name() string {
	return "SkillManage"
}

// Description shown to the LLM.
func (t *SkillManageTool) Description() string {
	return `Create or manage autogenerated skills.

The target library is class-level: prefer enriching an existing umbrella skill
over creating a narrow one-session skill. Preserve specific context in a labeled
SKILL.md subsection or a references/, templates/, scripts/, or assets/ support file.

Actions:
  - create: Create a new class-level umbrella only when no loaded or existing skill covers the workflow. Never overwrite an existing skill.
  - patch: Patch an existing skill immediately when you find it outdated, incomplete, or wrong — don't wait to be asked
  - write_file: Add narrow but valuable context under an existing umbrella skill
  - absorb_files: Carry support files from one skill package into another byte-for-byte. Use this when merging, NOT read_file+write_file.
  - read_file: Read one support file from an existing skill package
  - review: Record a completed review with no mutation when nothing reusable was learned
  - view: Load a skill's full instructions. When you view a skill, follow its instructions for the current task. If the skill needs updating, patch it immediately.
  - history: List immutable package revisions, newest first.
  - undo: Append a revert revision restoring a prior package state.
  - list: See all available skills with name, version, and description
  - archive: Recoverably archive a skill. Supply absorbed_into after consolidation, or pruning_reason when no knowledge was retained.

Parameters:
  - action: "create" | "patch" | "write_file" | "absorb_files" | "read_file" | "review" | "view" | "history" | "undo" | "list" | "archive"
  - name: skill identifier matching ^[a-z0-9]+(-[a-z0-9]+)*$ (max 64; "archive" and Windows device aliases are reserved)
  - description: what the skill does (create, patch)
  - instructions: the full skill body (create, patch; configured policy may impose a minimum)
  - append: append patch instructions instead of replacing them
  - tags: comma-separated discovery tags (optional, create)
  - category: organization category (optional, create)
  - file_path/file_content: support file path and content (write_file)
  - from_skill: skill whose support files are being carried across (absorb_files)
  - file_paths: comma-separated support paths to carry; omit to carry every support file (absorb_files)
  - absorbed_into/pruning_reason: archive provenance; one is required
  - dropped_files: comma-separated support paths you deliberately decline to carry, with archive; each must be justified in pruning_reason or the archive is refused
  - review_reason: why no skill mutation is appropriate (review)
  - offset/limit: optional Unicode character range for paged view output
  - expected_revision: revision returned by view; required for existing-skill mutations
  - revision: optional history revision to restore (undo defaults to the prior revision)

absorb_files copies bytes on disk. It is the ONLY correct way to move a script,
image, or other binary artifact between packages: read_file + write_file routes
the content through the model, which silently rewrites text and cannot represent
binary at all. archive with absorbed_into is refused when the source still has
support files the umbrella does not hold byte-for-byte.

Returns the skill path (create), updated skill info (patch), full skill content (view),
or a listing of all skills (list).`
}

