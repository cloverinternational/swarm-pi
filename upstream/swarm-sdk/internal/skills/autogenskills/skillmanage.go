// Execute handles the tool call.
func (t *SkillManageTool) Execute(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	action, _ := params["action"].(string)
	if t.isPreview() {
		switch action {
		case "list", "view", "read_file", "history", "review":
		default:
			return tools.NewToolResult(fmt.Sprintf("preview is read-only; SkillManage action %q is denied", action)), nil
		}
	}
	switch action {
	case "create":
		return t.executeCreate(ctx, params)
	case "patch":
		return t.executePatch(ctx, params)
	case "write_file":
		return t.executeWriteFile(ctx, params)
	case "absorb_files":
		return t.executeAbsorbFiles(ctx, params)
	case "read_file":
		return t.executeReadFile(ctx, params)
	case "review":
		reason, _ := params["review_reason"].(string)
		if strings.TrimSpace(reason) == "" {
			return tools.NewToolResult("review requires a non-empty 'review_reason'"), nil
		}
		return tools.NewToolResult(fmt.Sprintf("Skill review completed without mutation: %s", strings.TrimSpace(reason))), nil
	case "view":
		return t.executeView(ctx, params)
	case "history":
		return t.executeHistory(ctx, params)
	case "undo":
		return t.executeUndo(ctx, params)
	case "list":
		return t.executeList(params)
	case "archive":
		return t.executeArchive(ctx, params)
	default:
		return tools.NewToolResult(fmt.Sprintf("Unknown action %q. Use create, patch, write_file, absorb_files, read_file, review, view, history, undo, list, or archive.", action)), nil
	}
}

// executeCreate handles the create action.
func (t *SkillManageTool) executeCreate(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	desc, _ := params["description"].(string)
	instr, _ := params["instructions"].(string)
	tagsStr, _ := params["tags"].(string)
	category, _ := params["category"].(string)

	var tags []string
	if tagsStr != "" {
		for tag := range strings.SplitSeq(tagsStr, ",") {
			if trimmed := strings.TrimSpace(tag); trimmed != "" {
				tags = append(tags, trimmed)
			}
		}
	}

	opts := CreateOptions{
		Name:          name,
		Description:   desc,
		Instructions:  instr,
		Tags:          tags,
		Category:      category,
		TriggerReason: TriggerLLMNudge,
	}

	result, revision := t.svc.CreateSkillRevisioned(ctx, opts)
	if !result.IsSuccess() {
		return tools.NewToolResult(fmt.Sprintf("Skill creation failed: %v", result.Error)), nil
	}

	// Seed the curator's lifecycle record at creation time so the new skill
	// starts its stale/archive clock from now.
	t.svc.MarkSkillUsed(name)

	return tools.NewToolResult(fmt.Sprintf("Created skill %q at %s\nRevision: %s", result.Skill.Metadata.Name, result.Path, revision)), nil
}

// executePatch handles the patch action (Phase 3).
func (t *SkillManageTool) executePatch(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	if name == "" {
		return tools.NewToolResult("patch requires a 'name' parameter"), nil
	}
	if refusal := t.ensureWritable(name); refusal != "" {
		return tools.NewToolResult(refusal), nil
	}

	instructions, _ := params["instructions"].(string)
	description, _ := params["description"].(string)
	appendMode, _ := params["append"].(bool) // optional: append vs replace
	expected, _ := params["expected_revision"].(string)

	var tags []string
	if tagsStr, _ := params["tags"].(string); tagsStr != "" {
		for t := range strings.SplitSeq(tagsStr, ",") {
			if trimmed := strings.TrimSpace(t); trimmed != "" {
				tags = append(tags, trimmed)
			}
		}
	}

	opts := PatchOptions{
		Name:               name,
		Instructions:       instructions,
		Description:        description,
		AppendInstructions: appendMode,
		Tags:               tags,
		TriggerReason:      TriggerLLMNudge,
	}

	result, revision := t.svc.PatchSkillRevisioned(ctx, opts, expected)
	if !result.IsSuccess() {
		return tools.NewToolResult(fmt.Sprintf("Patch failed: %v", result.Error)), nil
	}

	// Patching is activity: it feeds the same stale/archive clock as a use
	// (mirrors Hermes' bump_patch → latest_activity_at).
	t.svc.MarkSkillUsed(name)

	return tools.NewToolResult(fmt.Sprintf(
		"Patched skill %q (v%s → v%s) at %s",
		result.Skill.Metadata.Name,
		result.PreviousVersion,
		result.NewVersion,
		result.Path+"\nRevision: "+revision,
	)), nil
}

// executeWriteFile stores narrow experiential knowledge inside an existing
// class-level skill package instead of creating another top-level skill.
func (t *SkillManageTool) executeWriteFile(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	relativePath, _ := params["file_path"].(string)
	content, _ := params["file_content"].(string)
	expected, _ := params["expected_revision"].(string)
	if name == "" || relativePath == "" {
		return tools.NewToolResult("write_file requires 'name' and 'file_path'"), nil
	}
	if refusal := t.ensureWritable(name); refusal != "" {
		return tools.NewToolResult(refusal), nil
	}
	if content == "" {
		return tools.NewToolResult("write_file requires non-empty 'file_content'"), nil
	}
	target, revision, err := t.svc.WriteSupportFileRevisioned(ctx, name, relativePath, []byte(content), expected)
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("write_file failed: %v", err)), nil
	}
	t.svc.MarkSkillUsed(name)
	return tools.NewToolResult(fmt.Sprintf("Wrote support file for %q at %s\nRevision: %s", name, target, revision)), nil
}

// executeAbsorbFiles carries support files between packages byte-for-byte.
//
// The bytes never enter the model's context or output. That is the entire
// reason this action exists: the read_file + write_file path made a language
// model retype every carried artifact, which drifts text and cannot represent
// binary content such as images or compiled files at all.
func (t *SkillManageTool) executeAbsorbFiles(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	fromSkill, _ := params["from_skill"].(string)
	expected, _ := params["expected_revision"].(string)
	if name == "" || fromSkill == "" {
		return tools.NewToolResult("absorb_files requires 'from_skill' (source) and 'name' (destination umbrella)"), nil
	}
	if refusal := t.ensureWritable(name); refusal != "" {
		return tools.NewToolResult(refusal), nil
	}
	if _, err := t.svc.ViewSkill(fromSkill); err != nil {
		return tools.NewToolResult(fmt.Sprintf("absorb_files source %q does not exist: %v", fromSkill, err)), nil
	}
	if _, err := t.svc.ViewSkill(name); err != nil {
		return tools.NewToolResult(fmt.Sprintf("absorb_files destination %q does not exist: %v", name, err)), nil
	}

	outcomes, revision, err := t.svc.absorbSupportFiles(ctx, fromSkill, name, splitList(params["file_paths"]), expected)
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("absorb_files failed: %v", err)), nil
	}
	t.svc.MarkSkillUsed(name)

	var b strings.Builder
	fmt.Fprintf(&b, "Absorbed %d support file(s) from %q into %q, byte-for-byte:\n", len(outcomes), fromSkill, name)
	var copied int
	for _, out := range outcomes {
		if out.Skipped != "" {
			fmt.Fprintf(&b, "  = %s (%d bytes, %s)\n", out.RelPath, out.Size, out.Skipped)
			continue
		}
		copied++
		fmt.Fprintf(&b, "  + %s (%d bytes, sha256:%s)\n", out.RelPath, out.Size, short(out.Digest))
	}
	if revision != "" {
		fmt.Fprintf(&b, "Revision: %s\n", revision)
	}
	if copied > 0 {
		b.WriteString("Every copy was verified by re-hashing the destination.\n")
	}
	b.WriteString("Now update the destination instructions to reference the new paths.")
	return tools.NewToolResult(b.String()), nil
}

// splitList parses a comma-separated tool parameter into trimmed entries.
func splitList(raw any) []string {
	text, _ := raw.(string)
	if strings.TrimSpace(text) == "" {
		return nil
	}
	var out []string
	for _, part := range strings.Split(text, ",") {
		if trimmed := strings.TrimSpace(part); trimmed != "" {
			out = append(out, trimmed)
		}
	}
	return out
}

func (t *SkillManageTool) executeReadFile(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	relativePath, _ := params["file_path"].(string)
	if name == "" || relativePath == "" {
		return tools.NewToolResult("read_file requires 'name' and 'file_path'"), nil
	}
	data, revision, external, err := t.svc.readSupportFileRevisionSnapshot(ctx, name, relativePath, t.isPreview())
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("read_file failed: %v", err)), nil
	}
	if !t.isPreview() {
		t.svc.MarkSkillUsed(name)
	}
	note := ""
	if external {
		note = "\nNOTE: This revision represents live external/untracked state. Use this newly viewed revision for the next mutation to reconcile it explicitly."
	}
	return tools.NewToolResult(fmt.Sprintf("═══ SUPPORT FILE: %s/%s ═══\nRevision: %s%s\n%s", name, filepath.ToSlash(filepath.Clean(relativePath)), revision, note, data)), nil
}

// resolveSupportPath rejects ordinary traversal and symlink escapes. It does
// not provide descriptor-relative traversal, so a hostile local process with
// write access to the package can still race path components between checks.
func resolveSupportPath(autogenDir, name, relativePath string) (string, error) {
	if !isSafeSkillDirName(name) {
		return "", fmt.Errorf("unsafe skill name")
	}
	clean := filepath.Clean(relativePath)
	if filepath.IsAbs(clean) || clean == "." || clean == ".." ||
		strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("path must stay inside the skill package")
	}
	first, _, _ := strings.Cut(filepath.ToSlash(clean), "/")
	allowed := map[string]bool{"references": true, "templates": true, "scripts": true, "assets": true}
	if !allowed[first] {
		return "", fmt.Errorf("path must begin with references/, templates/, scripts/, or assets/")
	}
	root := filepath.Join(autogenDir, name)
	rootInfo, err := os.Lstat(root)
	if err != nil {
		return "", err
	}
	if rootInfo.Mode()&os.ModeSymlink != 0 || !rootInfo.IsDir() {
		return "", fmt.Errorf("skill package must be a real directory")
	}
	current := root
	parts := strings.Split(filepath.ToSlash(clean), "/")
	for index, part := range parts {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if os.IsNotExist(err) {
			break
		}
		if err != nil {
			return "", err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return "", fmt.Errorf("symlink rejected in skill package: %s", filepath.ToSlash(filepath.Join(parts[:index+1]...)))
		}
		if index < len(parts)-1 && !info.IsDir() {
			return "", fmt.Errorf("support path component is not a directory: %s", part)
		}
		if index == len(parts)-1 && !info.Mode().IsRegular() {
			return "", fmt.Errorf("unsupported filesystem entry: %s", part)
		}
	}
	return filepath.Join(root, clean), nil
}

// executeView handles the view action.
func (t *SkillManageTool) executeView(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	if name == "" {
		return tools.NewToolResult("view requires a 'name' parameter"), nil
	}

	skill, revision, supportFiles, external, err := t.svc.viewSkillRevisionSnapshot(ctx, name, t.isPreview())
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("Failed to view skill: %v", err)), nil
	}

	// A view counts as a use (mirrors Hermes' _skill_view_with_bump): it
	// resets the skill's stale/archive clock. Without this, the curator
	// sub-agent's own inspections never register as activity and the same
	// skills get re-flagged stale on every run.
	if !t.isPreview() {
		t.svc.MarkSkillUsed(name)
	}
	t.mu.Lock()
	t.viewed[name] = true
	t.mu.Unlock()

	totalChars := utf8.RuneCountInString(skill.Instructions)
	offset, hasOffset := skillManageIntParam(params, "offset")
	limit, hasLimit := skillManageIntParam(params, "limit")
	if hasOffset && offset < 0 {
		return tools.NewToolResult("view 'offset' must be non-negative"), nil
	}
	if hasLimit && limit <= 0 {
		return tools.NewToolResult("view 'limit' must be positive"), nil
	}
	paged := hasOffset || hasLimit || totalChars > viewInstructionPageLimit
	if !hasOffset {
		offset = 0
	}
	if offset > totalChars {
		offset = totalChars
	}
	if !hasLimit || limit > viewInstructionPageLimit {
		limit = viewInstructionPageLimit
	}
	end := min(offset+limit, totalChars)
	instructions := skill.Instructions
	if paged {
		instructions, end = sliceRunesBounded(skill.Instructions, offset, end, viewInstructionPageLimit)
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("═══ SKILL: %s — Follow these instructions ═══\n", skill.Metadata.Name))
	b.WriteString(fmt.Sprintf("# %s\n", skill.Metadata.Name))
	b.WriteString(fmt.Sprintf("Version: %s\n", skill.Metadata.Version))
	b.WriteString(fmt.Sprintf("Description: %s\n", skill.Metadata.Description))
	if len(skill.Metadata.Tags) > 0 {
		b.WriteString(fmt.Sprintf("Tags: %s\n", strings.Join(skill.Metadata.Tags, ", ")))
	}
	b.WriteString(fmt.Sprintf("Source: %s\n", skill.Source))
	b.WriteString(fmt.Sprintf("Revision: %s\n", revision))
	if paged {
		fmt.Fprintf(&b, "expected_revision: %s\n", revision)
		fmt.Fprintf(&b, "Instructions range: [%d,%d) of %d Unicode characters\n", offset, end, totalChars)
	}
	if external {
		b.WriteString("NOTE: This revision represents live external/untracked state. Use this newly viewed revision for the next mutation to reconcile it explicitly.\n")
	}
	b.WriteString("\n")
	b.WriteString(instructions)
	if len(supportFiles) > 0 {
		b.WriteString("\n\nSupport files (load only when needed with SkillManage action=read_file):\n")
		for _, path := range supportFiles {
			b.WriteString("- " + path + "\n")
		}
	}
	b.WriteString(fmt.Sprintf("\n═══ If anything above is outdated or incorrect, call SkillManage(action: \"patch\", name: \"%s\", ...) immediately. ═══\n", skill.Metadata.Name))

	return tools.NewToolResult(b.String()), nil
}

func skillManageIntParam(params map[string]any, key string) (int, bool) {
	value, ok := params[key]
	if !ok {
		return 0, false
	}
	switch number := value.(type) {
	case int:
		return number, true
	case int64:
		return int(number), true
	case float64:
		return int(number), true
	default:
		return 0, false
	}
}

func sliceRunesBounded(input string, start, end, maxBytes int) (string, int) {
	if start == end {
		return "", end
	}
	startByte := byteIndexForRune(input, start)
	endByte := byteIndexForRune(input, end)
	if endByte-startByte > maxBytes {
		endByte = startByte + maxBytes
		for endByte > startByte && !utf8.RuneStart(input[endByte]) {
			endByte--
		}
		end = start + utf8.RuneCountInString(input[startByte:endByte])
	}
	return input[startByte:endByte], end
}

func byteIndexForRune(input string, target int) int {
	runeIndex := 0
	for byteIndex := range input {
		if runeIndex == target {
			return byteIndex
		}
		runeIndex++
	}
	return len(input)
}

func (t *SkillManageTool) executeHistory(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	if name == "" {
		return tools.NewToolResult("history requires a 'name' parameter"), nil
	}
	var revisions []SkillRevision
	var err error
	if t.isPreview() {
		revisions, err = t.svc.SkillHistoryReadOnly(name)
	} else {
		revisions, err = t.svc.SkillHistory(ctx, name)
	}
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("History failed: %v", err)), nil
	}
	// revisions is newest-first (see SkillHistory's doc comment). "limit" is
	// documented at the top level as "Maximum Unicode characters returned by
	// view", but callers reasonably read a bare {action:"history", limit:1}
	// as "give me N revisions" — and got the ENTIRE history back with no
	// indication limit was ignored (issue #278). Honor it here as a revision
	// count cap so the documented "or clearly reject" contract has a real
	// effect instead of being silently dropped.
	if limit, ok := skillManageIntParam(params, "limit"); ok {
		if limit < 1 {
			return tools.NewToolResult(fmt.Sprintf("limit must be >= 1, got %d", limit)), nil
		}
		if limit < len(revisions) {
			revisions = revisions[:limit]
		}
	}
	data, err := json.MarshalIndent(revisions, "", "  ")
	if err != nil {
		return nil, err
	}
	return tools.NewToolResult(string(data)), nil
}

func (t *SkillManageTool) executeUndo(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	expected, _ := params["expected_revision"].(string)
	revision, _ := params["revision"].(string)
	if name == "" {
		return tools.NewToolResult("undo requires a 'name' parameter"), nil
	}
	if refusal := t.ensureWritable(name); refusal != "" {
		return tools.NewToolResult(refusal), nil
	}
	newRevision, err := t.svc.UndoSkill(ctx, name, expected, revision)
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("Undo failed: %v", err)), nil
	}
	return tools.NewToolResult(fmt.Sprintf("Restored skill %q\nRevision: %s", name, newRevision)), nil
}

// executeList handles the list action.
func (t *SkillManageTool) executeList(params map[string]any) (*tools.ToolResult, error) {
	skillList := t.svc.ListSkills()
	if len(skillList) == 0 {
		return tools.NewToolResult("No autogenerated skills exist yet. Use 'create' to make your first skill."), nil
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("Found %d autogenerated skill(s):\n\n", len(skillList)))
	for _, s := range skillList {
		version := s.Metadata.Version
		if version == "" {
			version = "?.?.?"
		}
		b.WriteString(fmt.Sprintf("- **%s** (v%s): %s\n", s.Metadata.Name, version, s.Metadata.Description))
	}
	return tools.NewToolResult(b.String()), nil
}

// executeArchive handles the archive action.
func (t *SkillManageTool) executeArchive(ctx context.Context, params map[string]any) (*tools.ToolResult, error) {
	name, _ := params["name"].(string)
	if name == "" {
		return tools.NewToolResult("archive requires a 'name' parameter"), nil
	}
	if refusal := t.ensureWritable(name); refusal != "" {
		return tools.NewToolResult(refusal), nil
	}
	absorbedInto, _ := params["absorbed_into"].(string)
	pruningReason, _ := params["pruning_reason"].(string)
	expected, _ := params["expected_revision"].(string)
	if strings.TrimSpace(absorbedInto) == "" && strings.TrimSpace(pruningReason) == "" {
		return tools.NewToolResult("archive requires 'absorbed_into' after consolidation or 'pruning_reason' for true pruning"), nil
	}
	if absorbedInto == name {
		return tools.NewToolResult("archive absorbed_into must name a different umbrella skill"), nil
	}
	if absorbedInto != "" {
		if _, err := t.svc.ViewSkill(absorbedInto); err != nil {
			return tools.NewToolResult(fmt.Sprintf("archive umbrella %q does not exist: %v", absorbedInto, err)), nil
		}
	}
	// Preservation precondition. Archiving into an umbrella that does not hold
	// the source's support files byte-for-byte is silent data loss, and it was
	// the dominant failure mode measured in the curator benchmark: prose
	// survived a merge while scripts, assets and other concrete artifacts did
	// not. Deliberate drops stay possible, but only when named and justified.
	if absorbedInto != "" {
		if dir := t.svc.GetConfig().AutogenDir; dir != "" {
			missing, err := missingSupportFiles(dir, name, absorbedInto)
			if err != nil {
				return tools.NewToolResult(fmt.Sprintf("archive preservation check failed: %v", err)), nil
			}
			dropped := splitList(params["dropped_files"])
			if remaining := excludeDropped(missing, dropped); len(remaining) > 0 {
				return tools.NewToolResult(fmt.Sprintf(
					"Archive refused: %q still has %d support file(s) that %q does not hold byte-for-byte:\n  %s\n\n"+
						"Carry them across first, without retyping them:\n"+
						"  SkillManage(action=\"absorb_files\", from_skill=%q, name=%q)\n"+
						"then rewrite the umbrella's instructions to the new paths and archive again.\n"+
						"If a file is genuinely obsolete, name it in 'dropped_files' and justify the loss in 'pruning_reason'.",
					name, len(remaining), absorbedInto, strings.Join(remaining, "\n  "),
					name, absorbedInto)), nil
			}
			if len(dropped) > 0 && strings.TrimSpace(pruningReason) == "" {
				return tools.NewToolResult("archive with 'dropped_files' requires 'pruning_reason' explaining why losing those files is safe"), nil
			}
		}
	}

	curator := t.svc.GetCurator()
	if curator == nil {
		return tools.NewToolResult("archiving not available: no curator configured"), nil
	}

	autogenDir := t.svc.GetConfig().AutogenDir
	if autogenDir == "" {
		return tools.NewToolResult("archiving not available: no autogen directory configured"), nil
	}

	path, revision, err := t.svc.ArchiveSkillRevisioned(ctx, name, absorbedInto, pruningReason, expected)
	if err != nil {
		return tools.NewToolResult(fmt.Sprintf("Archive failed: %v", err)), nil
	}
	if t.svc.factory != nil && t.svc.factory.registry != nil {
		t.svc.factory.registry.Unload(name)
	}

	return tools.NewToolResult(fmt.Sprintf("Archived skill %q to %s\nRevision: %s", name, path, revision)), nil
}

