// Package vocab scores agent language around tool failures against a versioned,
// regenerable marker artifact.
//
// Why an artifact instead of constants: the measured vocabulary decays. A
// precision-seeking cluster that dominated failure prose in early 2026 fell from
// 9.6x to 0.98x lift within four months, and the intuitive failure words
// (fallback 0.55x, confirm 0.20x, verify 0.32x, problem 0.28x) are ANTI-correlated
// with failure. Compiled-in keywords would therefore ship a detector that is wrong
// on arrival and rots silently. The artifact carries its own training window and
// support counts so CI can regenerate it and diff the drift.
//
// The scorer records features; it does not decide. Callers persist observations
// and let offline analysis fit thresholds.
package vocab

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"strings"
	"sync"
)

// Marker is a single scored phrase with the evidence behind it.
type Marker struct {
	Phrase string  `json:"phrase"`
	Lift   float64 `json:"lift"`
	// DF is the number of failure documents containing the phrase. Markers
	// below the artifact's MinimumSupport are not loaded.
	DF int `json:"df"`
	// Echo is the share of the phrase's content words already present in the
	// preceding error text. High echo means the model quoted the diagnosis
	// rather than generating it, which is a weaker behavioural signal.
	Echo float64 `json:"echo"`
}

// Artifact is the versioned marker set. Regenerated by cmd/vocab-train.
type Artifact struct {
	Schema int `json:"schema"`
	// TrainedThrough bounds the corpus. A consumer older than the artifact is
	// fine; an artifact much older than the runtime is the decay case CI exists
	// to surface.
	TrainedThrough string `json:"trained_through"`
	Corpus         struct {
		FailureDocs int `json:"failure_docs"`
		ControlDocs int `json:"control_docs"`
	} `json:"corpus"`
	MinimumSupport int `json:"minimum_support"`
	// Elevated phrases are more likely after a failure (lift > 1).
	Elevated []Marker `json:"elevated"`
	// Suppressed phrases are LESS likely after a failure (lift < 1). These are
	// the reliable signal: `now` is 0.13x in prose and 0.09x in thinking and is
	// the top suppressed marker in every model family measured. Absence of the
	// success register beats presence of any failure register.
	Suppressed []Marker `json:"suppressed"`
	// Channel is "prose" or "thinking"; the registers differ materially and
	// must not be pooled.
	Channel string `json:"channel"`
}

// Score is the per-message feature vector. It is intentionally raw counts plus
// normalised rates: thresholds belong to offline analysis, not to this package.
type Score struct {
	Words           int      `json:"words"`
	ElevatedHits    int      `json:"elevated_hits"`
	SuppressedHits  int      `json:"suppressed_hits"`
	ElevatedMatched []string `json:"elevated_matched,omitempty"`
	// SuppressionScore is 1 - (suppressed markers observed / suppressed markers
	// known). It rises as the success register goes missing, which is the
	// direction that actually tracks failure.
	SuppressionScore float64 `json:"suppression_score"`
	// EchoWeighted discounts elevated hits by their echo rate, so a message that
	// merely quotes the error scores lower than one that generates new language.
	EchoWeighted float64 `json:"echo_weighted_elevated"`
	ArtifactAge  string  `json:"artifact_trained_through,omitempty"`
}

// Scorer holds compiled matchers for one artifact.
type Scorer struct {
	art        Artifact
	elevated   []compiled
	suppressed []compiled
}

type compiled struct {
	re     *regexp.Regexp
	marker Marker
}

func compileMarkers(ms []Marker, minSupport int) []compiled {
	out := make([]compiled, 0, len(ms))
	for _, m := range ms {
		if m.DF < minSupport || strings.TrimSpace(m.Phrase) == "" {
			continue
		}
		// Word-bounded, whitespace-tolerant phrase match. QuoteMeta keeps
		// artifact content inert: a marker is data, never a pattern.
		parts := strings.Fields(strings.ToLower(m.Phrase))
		for i, p := range parts {
			parts[i] = regexp.QuoteMeta(p)
		}
		re, err := regexp.Compile(`(?i)\b` + strings.Join(parts, `\s+`) + `\b`)
		if err != nil {
			continue
		}
		out = append(out, compiled{re: re, marker: m})
	}
	return out
}

// New builds a Scorer from an in-memory artifact.
func New(art Artifact) *Scorer {
	min := art.MinimumSupport
	if min <= 0 {
		min = 1
	}
	return &Scorer{
		art:        art,
		elevated:   compileMarkers(art.Elevated, min),
		suppressed: compileMarkers(art.Suppressed, min),
	}
}

// Load reads an artifact from disk.
func Load(path string) (*Scorer, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read vocab artifact: %w", err)
	}
	var art Artifact
	if err := json.Unmarshal(raw, &art); err != nil {
		return nil, fmt.Errorf("parse vocab artifact: %w", err)
	}
	if art.Schema != 1 {
		return nil, fmt.Errorf("unsupported vocab artifact schema %d", art.Schema)
	}
	return New(art), nil
}

// TrainedThrough exposes the artifact's training bound for provenance.
func (s *Scorer) TrainedThrough() string { return s.art.TrainedThrough }

// Channel reports which register this artifact was fitted on.
func (s *Scorer) Channel() string { return s.art.Channel }

var wordSplit = regexp.MustCompile(`\S+`)

// Score computes features for one message body. A nil Scorer yields a zero
// Score so an unconfigured deployment degrades to "no vocabulary features"
// rather than to an error on the hook path.
func (s *Scorer) Score(text string) Score {
	if s == nil || strings.TrimSpace(text) == "" {
		return Score{}
	}
	body := strings.ToLower(text)
	sc := Score{
		Words:       len(wordSplit.FindAllString(body, -1)),
		ArtifactAge: s.art.TrainedThrough,
	}
	for _, c := range s.elevated {
		if c.re.MatchString(body) {
			sc.ElevatedHits++
			sc.EchoWeighted += 1 - c.marker.Echo
			if len(sc.ElevatedMatched) < 16 {
				sc.ElevatedMatched = append(sc.ElevatedMatched, c.marker.Phrase)
			}
		}
	}
	for _, c := range s.suppressed {
		if c.re.MatchString(body) {
			sc.SuppressedHits++
		}
	}
	if n := len(s.suppressed); n > 0 {
		sc.SuppressionScore = 1 - float64(sc.SuppressedHits)/float64(n)
	}
	return sc
}

var (
	defaultMu sync.RWMutex
	defaults  = map[string]*Scorer{}
)

// SetDefault installs the process-wide scorer for a channel ("prose" or
// "thinking"). Hooks read through Default so a deployment without artifacts is
// silently featureless instead of broken.
func SetDefault(channel string, s *Scorer) {
	defaultMu.Lock()
	defaults[channel] = s
	defaultMu.Unlock()
}

// Default returns the scorer for a channel, or nil.
func Default(channel string) *Scorer {
	defaultMu.RLock()
	defer defaultMu.RUnlock()
	return defaults[channel]
}
